"""I contatori (sequenze) di PostgreSQL restano indietro quando gli id si
scrivono a mano: le schede di pyArchInit scrivono MAX + 1, l'import da QField
anche. Il primo record con l'id di default (un poligono disegnato in QGIS,
un documento ricavato dal 3D) prenderebbe un id già usato. ``db_sequences``
rimette il contatore in pari, trovandolo dal DEFAULT della colonna anche
quando non è OWNED BY (lo schema del plugin per i gid). Schemi temporanei di
pyarchinit_test_pg: gli altri database del server non si toccano."""
from __future__ import annotations

import sys
import uuid
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[2]
for p in (str(_ROOT / "ext_libs"), str(_ROOT)):
    if p not in sys.path:
        sys.path.insert(0, p)

from tests.sync.conftest_pg import PG_CONN_STR  # noqa: E402


@pytest.fixture
def schema():
    from sqlalchemy import create_engine, text
    nome = "seq_" + uuid.uuid4().hex[:8]
    base = create_engine(PG_CONN_STR)
    try:
        with base.begin() as conn:
            conn.execute(text("CREATE SCHEMA %s" % nome))
    except Exception as e:                              # noqa: BLE001
        pytest.skip("PostgreSQL di prova non raggiungibile: %s" % e)
    eng = create_engine(PG_CONN_STR, connect_args={"options": "-csearch_path=%s" % nome})
    yield eng
    eng.dispose()
    with base.begin() as conn:
        conn.execute(text("DROP SCHEMA %s CASCADE" % nome))
    base.dispose()


def _sql(eng, *istruzioni):
    from sqlalchemy import text
    with eng.begin() as conn:
        for s in istruzioni:
            conn.execute(text(s))


def _max(eng, tabella, colonna):
    from sqlalchemy import text
    with eng.connect() as conn:
        return conn.execute(text("SELECT MAX(%s) FROM %s" % (colonna, tabella))).scalar()


def test_la_sequenza_non_owned_si_trova_dal_default(schema):
    from modules.utility import db_sequences as dbs
    _sql(schema, "CREATE SEQUENCE t_gid_seq START 61400",
         "CREATE TABLE t (gid BIGINT DEFAULT nextval('t_gid_seq'::regclass) NOT NULL PRIMARY KEY, x TEXT)")
    with schema.connect() as conn:
        assert dbs.column_sequence(conn, "t", "gid").split(".")[-1].strip('"') == "t_gid_seq"


def test_un_contatore_indietro_torna_in_pari(schema):
    from modules.utility import db_sequences as dbs
    _sql(schema, "CREATE TABLE u (id_us SERIAL PRIMARY KEY, us TEXT)",
         "INSERT INTO u (id_us, us) VALUES (1, 'a'), (2, 'b'), (3, 'c')")      # come la scheda
    with schema.begin() as conn:
        assert dbs.sync_sequence(conn, "u", "id_us") is True
    _sql(schema, "INSERT INTO u (us) VALUES ('nuova')")                      # niente doppione
    assert _max(schema, "u", "id_us") == 4


def test_un_contatore_non_owned_indietro_torna_in_pari(schema):
    from modules.utility import db_sequences as dbs
    _sql(schema, "CREATE SEQUENCE t_gid_seq START 61400",
         "CREATE TABLE t (gid BIGINT DEFAULT nextval('t_gid_seq'::regclass) NOT NULL PRIMARY KEY, x TEXT)",
         "INSERT INTO t (x) VALUES ('disegnato in QGIS')",                      # 61400
         "INSERT INTO t (gid, x) VALUES (61401, 'da QField'), (61402, 'da QField')")
    with schema.begin() as conn:
        assert dbs.sync_sequence(conn, "t", "gid") is True
    _sql(schema, "INSERT INTO t (x) VALUES ('disegnato dopo')")
    assert _max(schema, "t", "gid") == 61403


def test_un_contatore_avanti_non_torna_indietro(schema):
    from modules.utility import db_sequences as dbs
    _sql(schema, "CREATE TABLE u (id SERIAL PRIMARY KEY, x TEXT)",
         "INSERT INTO u (x) VALUES ('a'), ('b'), ('c')", "DELETE FROM u")
    with schema.begin() as conn:
        assert dbs.sync_sequence(conn, "u", "id") is False
    _sql(schema, "INSERT INTO u (x) VALUES ('d')")
    assert _max(schema, "u", "id") == 4


def test_identity_e_colonne_senza_default(schema):
    from modules.utility import db_sequences as dbs
    _sql(schema, "CREATE TABLE v (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, x TEXT)",
         "INSERT INTO v (id, x) VALUES (1, 'a'), (2, 'b')",
         "CREATE TABLE w (id INT PRIMARY KEY)")
    with schema.begin() as conn:
        assert dbs.sync_sequence(conn, "v", "id") is True
        assert dbs.column_sequence(conn, "w", "id") is None
        assert dbs.sync_sequence(conn, "w", "id") is False
        assert dbs.sync_sequence(conn, "non_ce", "id") is False
    _sql(schema, "INSERT INTO v (x) VALUES ('c')")
    assert _max(schema, "v", "id") == 3


def test_le_colonne_col_nome_misto(schema):
    """«id_mediaToEntity» va citato: senza virgolette PostgreSQL lo cerca in minuscolo."""
    from modules.utility import db_sequences as dbs
    _sql(schema, 'CREATE TABLE "media_to_entity_table" ("id_mediaToEntity" SERIAL PRIMARY KEY, id_media INT)',
         'INSERT INTO media_to_entity_table ("id_mediaToEntity", id_media) VALUES (5, 1)')
    with schema.begin() as conn:
        assert dbs.sync_sequence(conn, "media_to_entity_table", "id_mediaToEntity") is True
    _sql(schema, "INSERT INTO media_to_entity_table (id_media) VALUES (2)")
    assert _max(schema, "media_to_entity_table", '"id_mediaToEntity"') == 6


def test_su_sqlite_non_fa_niente(tmp_path):
    from sqlalchemy import create_engine, text
    from modules.utility import db_sequences as dbs
    eng = create_engine("sqlite:///%s" % (tmp_path / "s.sqlite"))
    with eng.begin() as conn:
        conn.execute(text("CREATE TABLE t (gid INTEGER PRIMARY KEY, x TEXT)"))
        conn.execute(text("INSERT INTO t (gid, x) VALUES (7, 'a')"))
        assert dbs.column_sequence(conn, "t", "gid") is None
        assert dbs.sync_sequence(conn, "t", "gid") is False


